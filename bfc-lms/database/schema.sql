-- ------------------------------------------------------------
-- updated_at / last_viewed_at maintenance (MySQL ON UPDATE parity)
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION touch_timestamp() RETURNS trigger AS $$
BEGIN
  IF TG_ARGV[0] = 'last_viewed_at' THEN
    NEW.last_viewed_at := NOW();
  ELSE
    NEW.updated_at := NOW();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

